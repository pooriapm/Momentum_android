def build():
    anims = {"%s-%s" % (f, v) for f, vs in VARIANTS.items() for v in vs}
    seen_ids, seen_names = set(), {}
    problems = []
    out = []
    for e in E:
        assert e["id"] not in seen_ids, "duplicate id " + e["id"]
        seen_ids.add(e["id"])
        assert e["cat"] in CATEGORIES, e["id"]
        if e["anim"] is not None:
            assert e["anim"] in anims, "%s: no animation %s" % (e["id"], e["anim"])
        family = e["anim"].split("-")[0] if e["anim"] else None
        steps = e["steps"] or (FAMILY[family][0] if family in FAMILY else None)
        tip = e["tip"] or (FAMILY[family][1] if family in FAMILY else None)
        assert steps, e["id"] + " has no steps"
        for name in [e["fa"], e["en"]] + e["aka"]:
            key = name.strip().lower()
            if key in seen_names and seen_names[key] != e["id"]:
                problems.append("name '%s' used by %s and %s" % (name, seen_names[key], e["id"]))
            seen_names[key] = e["id"]
        item = {"id": e["id"], "fa": e["fa"], "en": e["en"], "cat": e["cat"], "muscles": e["muscles"], "steps": steps}
        if e["anim"]:
            item["anim"] = e["anim"]
        if e["eq"]:
            item["eq"] = e["eq"]
        if e["aka"]:
            item["aka"] = e["aka"]
        if tip:
            item["tip"] = tip
        out.append(item)
    if problems:
        sys.stderr.buffer.write(("\n".join(problems) + "\n").encode("utf-8"))
        sys.exit(1)
    return {"version": 1, "categories": CATEGORIES, "exercises": out}


def main():
    data = build()
    root = os.path.dirname(HERE)
    target = os.path.join(root, "exercise", "v1", "library.json")
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    # The app downloads the zip (about 25 KB); the JSON stays in git for review.
    info = zipfile.ZipInfo("library.json", date_time=(2026, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    with zipfile.ZipFile(target.replace(".json", ".zip"), "w") as z:
        z.writestr(info, text)
    counts = {}
    for e in data["exercises"]:
        counts[e["cat"]] = counts.get(e["cat"], 0) + 1
    animated = sum(1 for e in data["exercises"] if "anim" in e)
    print("%d exercises (%d animated), %.0f KB" % (len(data["exercises"]), animated, len(text.encode("utf-8")) / 1024))
    print(", ".join("%s %d" % (k, v) for k, v in sorted(counts.items(), key=lambda kv: -kv[1])))


if __name__ == "__main__":
    main()
